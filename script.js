const params = new URLSearchParams(window.location.search);
const languageSelect = document.querySelector('#language-select');
const message = document.querySelector('#form-message');
const formSubject = document.querySelector('#form-subject');
const formLanguage = document.querySelector('#form-language');
const formNext = document.querySelector('input[name="_next"]');
const metaDescription = document.querySelector('meta[name="description"]');

function setLanguage(language) {
  const lang = translations[language] ? language : 'en';
  const copy = translations[lang];

  document.documentElement.lang = lang;
  document.title = copy.pageTitle;
  if (metaDescription) metaDescription.setAttribute('content', copy.pageDescription);

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[key] !== undefined) element.textContent = copy[key];
  });

  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const key = element.dataset.i18nHtml;
    if (copy[key] !== undefined) element.innerHTML = copy[key];
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (copy[key] !== undefined) element.setAttribute('placeholder', copy[key]);
  });

  if (languageSelect) languageSelect.value = lang;
  if (formLanguage) formLanguage.value = lang === 'ru' ? 'Russian' : 'English';
  if (formSubject) formSubject.value = lang === 'ru' ? 'Новая заявка OwnerPathFuture — старт бизнеса' : 'New OwnerPathFuture Business Start Request';
  if (formNext) formNext.value = `https://ownerpathfuture-design.github.io/ownerpathfuture/?submitted=1&lang=${lang}#launch-plan`;

  try {
    localStorage.setItem('ownerPathFutureLanguage', lang);
  } catch (_) {
    // Language still works if storage is unavailable.
  }
}

let savedLanguage = 'en';
try {
  savedLanguage = localStorage.getItem('ownerPathFutureLanguage') || 'en';
} catch (_) {
  savedLanguage = 'en';
}

const initialLanguage = params.get('lang') || savedLanguage;
setLanguage(initialLanguage);

if (languageSelect) {
  languageSelect.addEventListener('change', (event) => setLanguage(event.target.value));
}

if (params.get('submitted') === '1' && message) {
  message.hidden = false;
}

document.querySelector('#year').textContent = new Date().getFullYear();

const offerEndsAt = new Date('2026-11-01T00:00:00-07:00');
const offerIsActive = new Date() < offerEndsAt;

if (!offerIsActive) {
  document.querySelectorAll('.promo-only').forEach((element) => {
    element.hidden = true;
  });
  document.querySelectorAll('.regular-price-after').forEach((element) => {
    element.hidden = false;
  });
}

const interestSelect = document.querySelector('#interest');

document.querySelectorAll('.plan-cta').forEach((link) => {
  link.addEventListener('click', () => {
    const plan = link.dataset.plan;
    if (interestSelect && plan) interestSelect.value = plan;

    if (typeof gtag === 'function' && plan) {
      gtag('event', 'select_plan', {
        plan_name: plan,
        promotion_active: offerIsActive
      });
    }
  });
});

document.querySelectorAll('a[href*="t.me/"]').forEach((link) => {
  link.addEventListener('click', () => {
    if (typeof gtag === 'function') {
      gtag('event', 'telegram_click', {
        link_location: link.closest('section')?.id || 'hero'
      });
    }
  });
});

const launchForm = document.querySelector('#launch-form');
if (launchForm) {
  launchForm.addEventListener('submit', () => {
    if (typeof gtag === 'function') {
      gtag('event', 'launch_form_submit', {
        plan_interest: interestSelect?.value || 'Not sure'
      });
    }
  });
}
